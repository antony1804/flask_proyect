
















c = float(input("Ingrese la temperatura en grados Celsius: "))  # Pedimos al usuario que ingrese la temperatura en grados Celsius
f = (c * 9/5) + 32  # Convertimos la temperatura a grados Fahrenheit usando la fórmula de conversión
print(f"{c}°C = {f:.2f}°F")  # Imprimimos el resultado de la conversión con dos

